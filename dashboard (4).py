    "            ],\n",
    "            value=years[0],\n",
    "            clearable=False\n",
    "        )\n",
    "    ], style={\"width\": \"50%\", \"margin\": \"auto\"}),\n",
    "\n",
    "    html.Br(),\n",
    "\n",
    "    html.Div(\n",
