    "                {\n",
    "                    \"label\": \"Recession Report Statistics\",\n",
    "                    \"value\": \"recession\"\n",
    "                },\n",
    "                {\n",
    "                    \"label\": \"Yearly Report Statistics\",\n",
    "                    \"value\": \"yearly\"\n",
    "                }\n",
    "            ],\n",
    "            value=\"recession\",\n",
    "            clearable=False\n",
    "        )\n",
