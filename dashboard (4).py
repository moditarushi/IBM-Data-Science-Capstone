    "            y=\"sales_volume\",\n",
    "            title=f\"Automobile Sales by Vehicle Type - {selected_year}\"\n",
    "        )\n",
    "\n",
    "        title = f\"Yearly Report Statistics - {selected_year}\"\n",
    "\n",
    "    return html.H3(title), fig\n",
